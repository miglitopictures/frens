// Accent marks, 2 rows tall. Centered over the base letter.
const MARKS = {
  acute: '..#|.#.',
  grave: '#..|.#.',
  circumflex: '.#.|#.#',
  tilde: '.#.#|#.#.',
  cedilla: '.#.|##.', // below the letter instead of above
}

// accented letter: [base, mark]
const ACCENTED = {
  á: ['a', 'acute'], à: ['a', 'grave'], â: ['a', 'circumflex'], ã: ['a', 'tilde'],
  é: ['e', 'acute'], ê: ['e', 'circumflex'],
  í: ['ı', 'acute'],
  ó: ['o', 'acute'], ô: ['o', 'circumflex'], õ: ['o', 'tilde'],
  ú: ['u', 'acute'],
  ç: ['c', 'cedilla'],
  Á: ['A', 'acute'], À: ['A', 'grave'], Â: ['A', 'circumflex'], Ã: ['A', 'tilde'],
  É: ['E', 'acute'], Ê: ['E', 'circumflex'],
  Í: ['I', 'acute'],
  Ó: ['O', 'acute'], Ô: ['O', 'circumflex'], Õ: ['O', 'tilde'],
  Ú: ['U', 'acute'],
  Ç: ['C', 'cedilla'],
}

// --- turn the strings above into lists of pixels: { width, pixels: [[x, y], ...] } ---

function parse(source) {
  const rows = source.split('|')
  const pixels = []
  rows.forEach((row, y) => {
    ;[...row].forEach((bit, x) => {
      if (bit === '#') pixels.push([x, y])
    })
  })
  return { width: rows[0].length, pixels }
}

const glyphs = {}
for (const char in GLYPHS) glyphs[char] = parse(GLYPHS[char])

for (const char in ACCENTED) {
  const [baseChar, markName] = ACCENTED[char]
  const base = glyphs[baseChar]
  const mark = parse(MARKS[markName])
  const dx = Math.floor((base.width - mark.width) / 2)
  // Where the mark goes (y of its top row):
  //   cedilla:          under the letter (rows 7-8)
  //   capital letters:  above the cap line (rows -3, -2)
  //   small letters:    above the x-height (rows -1, 0)
  let dy
  if (markName === 'cedilla') dy = 7
  else if (baseChar === baseChar.toUpperCase()) dy = -3
  else dy = -1
  glyphs[char] = {
    width: base.width,
    pixels: [...base.pixels, ...mark.pixels.map(([x, y]) => [x + dx, y + dy])],
  }
}

function glyphFor(char) {
  return glyphs[char] || glyphs['?']
}

// Width of one line of text in screen pixels.
export function measureText(text, scale = 1) {
  let width = 0
  for (const char of text) width += glyphFor(char).width + SPACING
  return Math.max(0, width - SPACING) * scale
}

// Calls plot(x, y) for every pixel of the text, at (x, y) = top-left of the line box.
// The renderer (screen.js) decides how a pixel is drawn.
export function layoutText(text, x, y, scale, plot) {
  let cursorX = x
  const top = y + TOP * scale
  for (const char of text) {
    const glyph = glyphFor(char)
    for (const [px, py] of glyph.pixels) plot(cursorX + px * scale, top + py * scale)
    cursorX += (glyph.width + SPACING) * scale
  }
}

// Splits text into lines that fit in maxWidth (screen pixels). Breaks on spaces.
export function wrapText(text, maxWidth, scale = 1) {
  const lines = []
  for (const paragraph of String(text).split('\n')) {
    let line = ''
    for (const word of paragraph.split(' ')) {
      const candidate = line ? line + ' ' + word : word
      if (line && measureText(candidate, scale) > maxWidth) {
        lines.push(line)
        line = word
      } else {
        line = candidate
      }
    }
    lines.push(line)
  }
  return lines
}
